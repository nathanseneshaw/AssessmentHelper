-- Database schema for the Assessment Helper.
-- Spring Data JDBC does not create tables, so Spring Boot runs this file at startup.
-- Tables are listed so that every foreign key points at a table created earlier.

CREATE TABLE IF NOT EXISTS school (
    school_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    school_name VARCHAR(200) NOT NULL
);

CREATE TABLE IF NOT EXISTS department (
    department_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    school_id INT NOT NULL REFERENCES school(school_id),
    department_name VARCHAR(100) NOT NULL,
    department_code VARCHAR(20) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS evaluation_policy (
    professor_rank VARCHAR(30) PRIMARY KEY,
    evaluation_interval_years INT NOT NULL,
    active_status BOOLEAN NOT NULL DEFAULT TRUE,
    made_date DATE,
    effective_date DATE,
    version BIGINT NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS professor (
    professor_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    department_id INT NOT NULL REFERENCES department(department_id),
    professor_rank VARCHAR(30) REFERENCES evaluation_policy(professor_rank),
    first_name VARCHAR(100) NOT NULL,
    last_name VARCHAR(100) NOT NULL,
    email VARCHAR(255) NOT NULL UNIQUE,
    hire_date DATE,
    active_status BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS committee_member (
    committee_member_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    professor_id INT NOT NULL UNIQUE REFERENCES professor(professor_id),
    start_date DATE NOT NULL,
    end_date DATE,
    active_status BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS user_account (
    user_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    professor_id INT UNIQUE REFERENCES professor(professor_id),
    username VARCHAR(100) NOT NULL UNIQUE,
    email VARCHAR(255) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS semester (
    semester_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    term VARCHAR(20) NOT NULL,
    academic_year INT NOT NULL,
    start_date DATE,
    end_date DATE
);

CREATE TABLE IF NOT EXISTS course (
    course_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    department_id INT NOT NULL REFERENCES department(department_id),
    course_code VARCHAR(20),
    course_number VARCHAR(20),
    course_name VARCHAR(200),
    course_level VARCHAR(30)
);

CREATE TABLE IF NOT EXISTS course_section (
    section_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_id INT NOT NULL REFERENCES course(course_id),
    semester_id INT NOT NULL REFERENCES semester(semester_id),
    section_number VARCHAR(20),
    meeting_days VARCHAR(20),
    start_time TIME,
    end_time TIME,
    location VARCHAR(100)
);

CREATE TABLE IF NOT EXISTS teaching_history (
    teaching_history_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    professor_id INT NOT NULL REFERENCES professor(professor_id),
    section_id INT NOT NULL REFERENCES course_section(section_id)
);

CREATE TABLE IF NOT EXISTS evaluation_cycle (
    cycle_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    semester_id INT NOT NULL REFERENCES semester(semester_id),
    signup_deadline DATE,
    observation_deadline DATE,
    feedback_deadline DATE,
    status VARCHAR(30)
);

CREATE TABLE IF NOT EXISTS evaluation_eligibility (
    eligibility_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    professor_id INT NOT NULL REFERENCES professor(professor_id),
    cycle_id INT NOT NULL REFERENCES evaluation_cycle(cycle_id),
    last_evaluation_date DATE,
    next_due_date DATE,
    eligibility_status VARCHAR(30),
    determined_at TIMESTAMP
);

CREATE TABLE IF NOT EXISTS evaluation_notification (
    notification_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    professor_id INT NOT NULL REFERENCES professor(professor_id),
    cycle_id INT NOT NULL REFERENCES evaluation_cycle(cycle_id),
    recipient VARCHAR(255) NOT NULL,
    subject VARCHAR(255) NOT NULL,
    body VARCHAR(16000) NOT NULL,
    sent_at TIMESTAMP NOT NULL
);

CREATE TABLE IF NOT EXISTS observer (
    observer_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    professor_id INT NOT NULL REFERENCES professor(professor_id),
    cycle_id INT NOT NULL REFERENCES evaluation_cycle(cycle_id),
    active_status BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS observee (
    observee_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    professor_id INT NOT NULL REFERENCES professor(professor_id),
    cycle_id INT NOT NULL REFERENCES evaluation_cycle(cycle_id),
    status VARCHAR(30)
);

CREATE TABLE IF NOT EXISTS evaluation_signup (
    signup_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    observee_id INT NOT NULL REFERENCES observee(observee_id),
    section_id INT NOT NULL REFERENCES course_section(section_id),
    signup_date DATE,
    status VARCHAR(30)
);

CREATE TABLE IF NOT EXISTS observer_match (
    match_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    signup_id INT NOT NULL REFERENCES evaluation_signup(signup_id),
    observer_id INT NOT NULL REFERENCES observer(observer_id),
    generated_date DATE,
    match_status VARCHAR(30)
);

CREATE UNIQUE INDEX IF NOT EXISTS observer_match_pair ON observer_match(signup_id, observer_id);

CREATE TABLE IF NOT EXISTS observer_request (
    request_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    signup_id INT NOT NULL REFERENCES evaluation_signup(signup_id),
    observer_id INT NOT NULL REFERENCES observer(observer_id),
    request_date TIMESTAMP,
    expiration_date TIMESTAMP,
    response_date TIMESTAMP,
    status VARCHAR(30)
);

CREATE TABLE IF NOT EXISTS observer_request_time (
    request_time_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id INT NOT NULL REFERENCES observer_request(request_id),
    proposed_date DATE,
    start_time TIME,
    end_time TIME,
    status VARCHAR(30)
);

CREATE TABLE IF NOT EXISTS observation_template (
    template_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_by INT REFERENCES user_account(user_id),
    template_name VARCHAR(200) NOT NULL,
    version INT,
    created_date DATE,
    active_status BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS observation_criterion (
    criterion_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    template_id INT NOT NULL REFERENCES observation_template(template_id),
    criterion_text VARCHAR(500) NOT NULL,
    question_type VARCHAR(30),
    required BOOLEAN NOT NULL DEFAULT TRUE,
    display_order INT,
    rating_min INT,
    rating_max INT,
    selected BOOLEAN NOT NULL DEFAULT TRUE,
    notes_enabled BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE IF NOT EXISTS observation (
    observation_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    signup_id INT NOT NULL REFERENCES evaluation_signup(signup_id),
    observer_id INT NOT NULL REFERENCES observer(observer_id),
    template_id INT NOT NULL REFERENCES observation_template(template_id),
    observation_date DATE,
    start_time TIME,
    status VARCHAR(30),
    observee_signed BOOLEAN NOT NULL DEFAULT FALSE,
    observer_signed BOOLEAN NOT NULL DEFAULT FALSE,
    observee_signed_at TIMESTAMP,
    observer_signed_at TIMESTAMP,
    completed_at TIMESTAMP,
    UNIQUE (signup_id, observer_id)
);

-- Persisted release state keeps randomized candidate lists stable across refreshes.
CREATE TABLE IF NOT EXISTS observer_list_state (
    signup_id INT PRIMARY KEY REFERENCES evaluation_signup(signup_id),
    window_start DATE NOT NULL,
    window_end DATE NOT NULL,
    released_at TIMESTAMP
);

CREATE TABLE IF NOT EXISTS observer_notification (
    notification_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    professor_id INT NOT NULL REFERENCES professor(professor_id),
    signup_id INT NOT NULL REFERENCES evaluation_signup(signup_id),
    message VARCHAR(1000) NOT NULL,
    created_at TIMESTAMP NOT NULL
);

CREATE TABLE IF NOT EXISTS observation_response (
    response_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    observation_id INT NOT NULL REFERENCES observation(observation_id),
    criterion_id INT NOT NULL REFERENCES observation_criterion(criterion_id),
    rating INT,
    comments VARCHAR(4000)
);

-- Append-only audit trail for observation records. Rows are only ever inserted: nothing in the application updates
-- or deletes them, and no entity or repository exposes them.
CREATE TABLE IF NOT EXISTS observation_audit_log (
    log_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    observation_id INT NOT NULL REFERENCES observation(observation_id),
    event_type VARCHAR(30) NOT NULL,
    actor_professor_id INT NOT NULL REFERENCES professor(professor_id),
    recipient_professor_id INT REFERENCES professor(professor_id),
    occurred_at TIMESTAMP NOT NULL
);

CREATE TABLE IF NOT EXISTS process_feedback (
    feedback_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cycle_id INT NOT NULL REFERENCES evaluation_cycle(cycle_id),
    professor_id INT NOT NULL REFERENCES professor(professor_id),
    signup_id INT REFERENCES evaluation_signup(signup_id),
    overall_rating INT,
    difficulties VARCHAR(4000),
    improvement_comments VARCHAR(4000),
    observee_comment VARCHAR(4000),
    submitted_date DATE
);

CREATE TABLE IF NOT EXISTS communication_thread (
    thread_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cycle_id INT REFERENCES evaluation_cycle(cycle_id),
    eligibility_id INT REFERENCES evaluation_eligibility(eligibility_id),
    signup_id INT REFERENCES evaluation_signup(signup_id),
    request_id INT REFERENCES observer_request(request_id),
    thread_type VARCHAR(30),
    subject VARCHAR(255),
    status VARCHAR(30),
    created_at TIMESTAMP,
    last_activity_at TIMESTAMP
);

CREATE TABLE IF NOT EXISTS message_template (
    template_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(200) NOT NULL,
    subject VARCHAR(255),
    body VARCHAR(4000),
    template_type VARCHAR(30),
    active_status BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS message (
    message_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    thread_id INT NOT NULL REFERENCES communication_thread(thread_id),
    template_id INT REFERENCES message_template(template_id),
    sender_user_id INT REFERENCES user_account(user_id),
    reply_to_message_id INT REFERENCES message(message_id),
    message_type VARCHAR(30),
    subject VARCHAR(255),
    message_body VARCHAR(4000),
    created_at TIMESTAMP
);

CREATE TABLE IF NOT EXISTS message_delivery (
    delivery_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    message_id INT NOT NULL REFERENCES message(message_id),
    recipient_user_id INT NOT NULL REFERENCES user_account(user_id),
    channel VARCHAR(30),
    delivery_status VARCHAR(30),
    sent_at TIMESTAMP,
    delivered_at TIMESTAMP,
    read_at TIMESTAMP
);

CREATE TABLE IF NOT EXISTS message_response (
    response_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    message_id INT NOT NULL REFERENCES message(message_id),
    user_id INT NOT NULL REFERENCES user_account(user_id),
    response_type VARCHAR(30),
    response_value VARCHAR(255),
    responded_at TIMESTAMP
);
